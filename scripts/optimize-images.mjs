/**
 * optimize-images.mjs
 *
 * Turns the original photographs in assets-src/originals/ into responsive
 * AVIF + WebP derivatives in public/images/ and writes a typed manifest
 * (src/data/images.generated.ts) with intrinsic sizes, a dominant colour and
 * a tiny blurred placeholder, so layouts never shift while images load.
 *
 *   node scripts/optimize-images.mjs
 *
 * Images are only ever resampled DOWN from the originals – nothing is
 * generated, retouched or upscaled.
 */
import sharp from 'sharp';
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'assets-src/originals');
const outDir = path.join(root, 'public/images');
const sources = JSON.parse(readFileSync(path.join(root, 'assets-src/image-sources.json'), 'utf8'));

const TARGET_WIDTHS = [400, 640, 960, 1200];

if (existsSync(outDir)) rmSync(outDir, { recursive: true });
mkdirSync(outDir, { recursive: true });

const hex = ({ r, g, b }) => '#' + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');
const manifest = {};
let totalBytes = 0;

async function emit(slug, input, { jpgOnly = false } = {}) {
  const meta = await sharp(input).metadata();
  const { width, height } = meta;

  if (jpgOnly) {
    const file = path.join(outDir, `${slug}.jpg`);
    const info = await sharp(input).jpeg({ quality: 82, mozjpeg: true }).toFile(file);
    totalBytes += info.size;
    return;
  }

  const widths = TARGET_WIDTHS.filter((w) => w < width);
  widths.push(width); // always include the native width, never larger
  for (const w of widths) {
    const base = sharp(input).resize({ width: w, withoutEnlargement: true });
    const a = await base.clone().avif({ quality: 52, effort: 6 }).toFile(path.join(outDir, `${slug}-${w}.avif`));
    const b = await base.clone().webp({ quality: 76, effort: 5 }).toFile(path.join(outDir, `${slug}-${w}.webp`));
    totalBytes += a.size + b.size;
  }

  const { dominant } = await sharp(input).stats();
  const lqipBuf = await sharp(input).resize({ width: 16 }).blur(1).webp({ quality: 40 }).toBuffer();

  manifest[slug] = {
    width,
    height,
    widths,
    color: hex(dominant),
    lqip: `data:image/webp;base64,${lqipBuf.toString('base64')}`,
  };
}

for (const img of sources.images) {
  await emit(img.slug, path.join(srcDir, img.file));
}
for (const crop of sources.crops) {
  const parent = sources.images.find((i) => i.slug === crop.from);
  const buf = await sharp(path.join(srcDir, parent.file)).extract(crop.region).png().toBuffer();
  await emit(crop.slug, buf, { jpgOnly: crop.jpgOnly });
}

const ts =
  `/* GENERATED by scripts/optimize-images.mjs – do not edit by hand. */\n` +
  `export interface ImageMeta {\n  width: number;\n  height: number;\n  widths: readonly number[];\n  color: string;\n  lqip: string;\n}\n\n` +
  `export const imageManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, ImageMeta>;\n\n` +
  `export type ImageSlug = keyof typeof imageManifest;\n`;
writeFileSync(path.join(root, 'src/data/images.generated.ts'), ts);

console.log(`${Object.keys(manifest).length} images → public/images (${(totalBytes / 1024 / 1024).toFixed(2)} MB total)`);
